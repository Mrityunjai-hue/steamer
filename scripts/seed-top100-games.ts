async function main() {
  console.log(`Starting bulk catalog injection for ${NEW_GAMES.length} blockbuster titles...`);

  let added = 0;
  let updated = 0;

  for (const g of NEW_GAMES) {
    const headerImage = `https://shared.akamai.steamstatic.com/store_item_assets/steam/apps/${g.steamAppId}/header.jpg`;
    const capsuleImage = `https://shared.akamai.steamstatic.com/store_item_assets/steam/apps/${g.steamAppId}/library_600x900.jpg`;
    const testedDate = new Date("2026-11-01T00:00:00.000Z");

    // Upsert series
    let seriesRecord = await prisma.series.upsert({
      where: { name: g.series },
      update: {},
      create: { name: g.series },
    });

    // Upsert game cleanly by unique title
    await prisma.game.upsert({
      where: { title: g.title },
      update: {
        seriesId: seriesRecord.id,
        steamAppId: g.steamAppId,
        releaseDate: g.releaseYear,
        genres: g.genres,
        steamPriceINR: g.steamPriceINR,
        hypeTier: g.hypeTier,
        launcher: g.launcher || "Steam only",
        offlineTag: "Offline OK",
        testedOfflineOn: testedDate,
        headerImage,
        capsuleImage,
      },
      create: {
        title: g.title,
        seriesId: seriesRecord.id,
        steamAppId: g.steamAppId,
        releaseDate: g.releaseYear,
        genres: g.genres,
        steamPriceINR: g.steamPriceINR,
        ourMonthlyPriceINR: g.hypeTier === "Hot" ? 99 : 79,
        hypeTier: g.hypeTier,
        launcher: g.launcher || "Steam only",
        offlineTag: "Offline OK",
        suggestedOfflineTag: "Offline OK",
        testedOfflineOn: testedDate,
        purchasableAsSingle: true,
        headerImage,
        capsuleImage,
      },
    });
    added++;
  }

  const totalInDb = await prisma.game.count();
  console.log(`✓ Completed catalog seeding! Added: ${added}, Updated: ${updated}. Total games in DB: ${totalInDb}`);
}

main()
  .catch((e) => {
    console.error("Seeding error:", e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });

